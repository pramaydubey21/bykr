-- =============================================================================
-- bykr — 01_schema.sql
-- All DDL: tables, keys, named constraints, indexes.
-- Rubric columns I (relational schema) and J (DDL with constraints).
--
-- Re-runnable: drops every bykr table first, so it applies cleanly to an empty
-- database AND re-applies over an existing one.
--
-- Design centre: ride_participant is the hub. Statuses, accident events (and
-- the MongoDB pings) reference a participant row, never (user, ride) pairs
-- separately, so it is structurally impossible to record data for a rider
-- who never joined the ride.
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS vector;

DROP TABLE IF EXISTS alert_audit, alert_recipient, sos_alert, accident_event,
                     rider_status, status_type, ride_waypoint, ride_summary,
                     ride_participant, ride, emergency_contact, authority,
                     friendship, role_permission, permission, user_role,
                     app_role, app_user CASCADE;

-- -----------------------------------------------------------------------------
-- Identity and access
-- -----------------------------------------------------------------------------
CREATE TABLE app_user (
    user_id        INT GENERATED BY DEFAULT AS IDENTITY,
    full_name      TEXT        NOT NULL,
    email          TEXT        NOT NULL,
    phone_no       TEXT,
    password_hash  TEXT        NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_app_user              PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_email        UNIQUE (email),
    CONSTRAINT chk_app_user_email_lower CHECK (email = lower(email)),
    CONSTRAINT chk_app_user_email_shape CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT chk_app_user_phone_shape CHECK (phone_no IS NULL OR phone_no ~ '^\+?[0-9 \-]{7,20}$'),
    CONSTRAINT chk_app_user_name_nonblank CHECK (length(btrim(full_name)) > 0),
    -- Argon2id encoded hashes always start with $argon2
    CONSTRAINT chk_app_user_hash_argon2 CHECK (password_hash LIKE '$argon2%')
);

CREATE TABLE app_role (
    role_id    INT GENERATED BY DEFAULT AS IDENTITY,
    role_name  TEXT NOT NULL,
    CONSTRAINT pk_app_role          PRIMARY KEY (role_id),
    CONSTRAINT uq_app_role_name     UNIQUE (role_name),
    CONSTRAINT chk_app_role_name    CHECK (role_name IN ('RIDER', 'ADMIN'))
);

CREATE TABLE user_role (
    user_id  INT NOT NULL,
    role_id  INT NOT NULL,
    CONSTRAINT pk_user_role         PRIMARY KEY (user_id, role_id),
    -- deleting a user removes their role grants; a role in use cannot be dropped
    CONSTRAINT fk_user_role_user    FOREIGN KEY (user_id) REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_role_role    FOREIGN KEY (role_id) REFERENCES app_role (role_id) ON DELETE RESTRICT
);
CREATE INDEX ix_user_role_role ON user_role (role_id);

CREATE TABLE permission (
    permission_id   INT GENERATED BY DEFAULT AS IDENTITY,
    permission_key  TEXT NOT NULL,
    CONSTRAINT pk_permission         PRIMARY KEY (permission_id),
    CONSTRAINT uq_permission_key     UNIQUE (permission_key),
    CONSTRAINT chk_permission_key_shape CHECK (permission_key ~ '^[a-z_]+:[a-z_]+$')
);

CREATE TABLE role_permission (
    role_id        INT NOT NULL,
    permission_id  INT NOT NULL,
    CONSTRAINT pk_role_permission            PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permission_role       FOREIGN KEY (role_id)       REFERENCES app_role (role_id)         ON DELETE CASCADE,
    CONSTRAINT fk_role_permission_permission FOREIGN KEY (permission_id) REFERENCES permission (permission_id) ON DELETE CASCADE
);
CREATE INDEX ix_role_permission_permission ON role_permission (permission_id);

-- -----------------------------------------------------------------------------
-- Social graph: friendship is a recursive relationship on app_user
-- -----------------------------------------------------------------------------
CREATE TABLE friendship (
    friendship_id  INT GENERATED BY DEFAULT AS IDENTITY,
    requester_id   INT         NOT NULL,
    addressee_id   INT         NOT NULL,
    link_state     TEXT        NOT NULL DEFAULT 'PENDING',
    requested_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    linked_at      TIMESTAMPTZ,
    CONSTRAINT pk_friendship              PRIMARY KEY (friendship_id),
    CONSTRAINT fk_friendship_requester    FOREIGN KEY (requester_id) REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_friendship_addressee    FOREIGN KEY (addressee_id) REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_friendship_not_self    CHECK (requester_id <> addressee_id),
    CONSTRAINT chk_friendship_link_state  CHECK (link_state IN ('PENDING', 'ACCEPTED', 'BLOCKED')),
    -- an ACCEPTED link must say when it was accepted; a PENDING one must not
    CONSTRAINT chk_friendship_linked_at   CHECK ((link_state = 'ACCEPTED') = (linked_at IS NOT NULL)),
    CONSTRAINT uq_friendship_ordered_pair UNIQUE (requester_id, addressee_id)
);
-- The ordered-pair constraint stops A->B twice; this stops A->B plus B->A.
CREATE UNIQUE INDEX ux_friendship_unordered_pair
    ON friendship (LEAST(requester_id, addressee_id), GREATEST(requester_id, addressee_id));
CREATE INDEX ix_friendship_addressee ON friendship (addressee_id);

-- -----------------------------------------------------------------------------
-- Rides
-- -----------------------------------------------------------------------------
CREATE TABLE ride (
    ride_id     INT GENERATED BY DEFAULT AS IDENTITY,
    created_by  INT         NOT NULL,
    ride_title  TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at  TIMESTAMPTZ,
    ended_at    TIMESTAMPTZ,
    ride_state  TEXT        NOT NULL DEFAULT 'CREATED',
    CONSTRAINT pk_ride                 PRIMARY KEY (ride_id),
    -- a user who created rides cannot be deleted out from under them
    CONSTRAINT fk_ride_created_by      FOREIGN KEY (created_by) REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_ride_state          CHECK (ride_state IN ('CREATED', 'ACTIVE', 'COMPLETED')),
    CONSTRAINT chk_ride_title_nonblank CHECK (length(btrim(ride_title)) BETWEEN 1 AND 120),
    CONSTRAINT chk_ride_end_after_start CHECK (ended_at IS NULL OR (started_at IS NOT NULL AND ended_at >= started_at)),
    -- state and timestamps must agree
    CONSTRAINT chk_ride_state_timestamps CHECK (
        (ride_state = 'CREATED'   AND started_at IS NULL     AND ended_at IS NULL) OR
        (ride_state = 'ACTIVE'    AND started_at IS NOT NULL AND ended_at IS NULL) OR
        (ride_state = 'COMPLETED' AND started_at IS NOT NULL AND ended_at IS NOT NULL)
    )
);
CREATE INDEX ix_ride_created_by ON ride (created_by);
CREATE INDEX ix_ride_state      ON ride (ride_state);

-- The hub. joined_at NULL means "invited, not yet joined".
CREATE TABLE ride_participant (
    participant_id  INT GENERATED BY DEFAULT AS IDENTITY,
    ride_id         INT         NOT NULL,
    user_id         INT         NOT NULL,
    invited_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    joined_at       TIMESTAMPTZ,
    left_at         TIMESTAMPTZ,
    is_leader       BOOLEAN     NOT NULL DEFAULT false,
    CONSTRAINT pk_ride_participant           PRIMARY KEY (participant_id),
    CONSTRAINT fk_ride_participant_ride      FOREIGN KEY (ride_id) REFERENCES ride (ride_id)     ON DELETE CASCADE,
    -- history is preserved: a user with ride history cannot be hard-deleted
    CONSTRAINT fk_ride_participant_user      FOREIGN KEY (user_id) REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT uq_ride_participant_ride_user UNIQUE (ride_id, user_id),
    CONSTRAINT chk_ride_participant_left_after_join CHECK (left_at IS NULL OR (joined_at IS NOT NULL AND left_at >= joined_at)),
    CONSTRAINT chk_ride_participant_leader_joined   CHECK (NOT is_leader OR joined_at IS NOT NULL)
);
-- exactly one leader per ride at most
CREATE UNIQUE INDEX ux_ride_participant_one_leader ON ride_participant (ride_id) WHERE is_leader;
CREATE INDEX ix_ride_participant_user ON ride_participant (user_id);

-- Downsampled route, written when a ride ends (from MongoDB pings) so that
-- fn_ride_distance_km and sp_end_ride can work in SQL. The raw, full-rate
-- telemetry stays in MongoDB.
CREATE TABLE ride_waypoint (
    ride_id      INT          NOT NULL,
    seq          INT          NOT NULL,
    latitude     NUMERIC(9,6) NOT NULL,
    longitude    NUMERIC(9,6) NOT NULL,
    speed_kmph   NUMERIC(6,2),
    recorded_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_ride_waypoint          PRIMARY KEY (ride_id, seq),
    CONSTRAINT fk_ride_waypoint_ride     FOREIGN KEY (ride_id) REFERENCES ride (ride_id) ON DELETE CASCADE,
    CONSTRAINT chk_ride_waypoint_seq     CHECK (seq >= 0),
    CONSTRAINT chk_ride_waypoint_lat     CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT chk_ride_waypoint_lon     CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT chk_ride_waypoint_speed   CHECK (speed_kmph IS NULL OR speed_kmph BETWEEN 0 AND 400)
);

-- -----------------------------------------------------------------------------
-- Status broadcasting
-- -----------------------------------------------------------------------------
CREATE TABLE status_type (
    type_id       INT GENERATED BY DEFAULT AS IDENTITY,
    status_label  TEXT NOT NULL,
    icon_name     TEXT NOT NULL,
    CONSTRAINT pk_status_type        PRIMARY KEY (type_id),
    CONSTRAINT uq_status_type_label  UNIQUE (status_label),
    CONSTRAINT chk_status_type_label CHECK (status_label IN ('REFUELLING', 'EATING', 'DELAYED', 'RIDING', 'STOPPED'))
);

CREATE TABLE rider_status (
    status_id       INT GENERATED BY DEFAULT AS IDENTITY,
    participant_id  INT         NOT NULL,
    type_id         INT         NOT NULL,
    set_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    cleared_at      TIMESTAMPTZ,
    CONSTRAINT pk_rider_status              PRIMARY KEY (status_id),
    CONSTRAINT fk_rider_status_participant  FOREIGN KEY (participant_id) REFERENCES ride_participant (participant_id) ON DELETE CASCADE,
    CONSTRAINT fk_rider_status_type         FOREIGN KEY (type_id)        REFERENCES status_type (type_id)              ON DELETE RESTRICT,
    CONSTRAINT chk_rider_status_cleared_after_set CHECK (cleared_at IS NULL OR cleared_at >= set_at)
);
-- at most one open (uncleared) status per participant
CREATE UNIQUE INDEX ux_rider_status_one_open ON rider_status (participant_id) WHERE cleared_at IS NULL;
CREATE INDEX ix_rider_status_type ON rider_status (type_id);

-- -----------------------------------------------------------------------------
-- Emergency contacts and authorities
-- -----------------------------------------------------------------------------
CREATE TABLE emergency_contact (
    contact_id     INT GENERATED BY DEFAULT AS IDENTITY,
    user_id        INT  NOT NULL,
    contact_name   TEXT NOT NULL,
    contact_phone  TEXT NOT NULL,
    relation       TEXT NOT NULL,
    CONSTRAINT pk_emergency_contact        PRIMARY KEY (contact_id),
    CONSTRAINT fk_emergency_contact_user   FOREIGN KEY (user_id) REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_emergency_contact_phone CHECK (contact_phone ~ '^\+?[0-9 \-]{7,20}$'),
    CONSTRAINT chk_emergency_contact_relation CHECK (relation IN ('PARENT', 'SPOUSE', 'SIBLING', 'FRIEND', 'RELATIVE', 'OTHER')),
    CONSTRAINT uq_emergency_contact_user_phone UNIQUE (user_id, contact_phone)
);

-- Authority records are DISPLAYED for a human to act on. bykr never contacts
-- a real emergency service. base_latitude/base_longitude/radius_km turn the
-- textual jurisdiction into something the alert trigger can match spatially.
CREATE TABLE authority (
    authority_id    INT GENERATED BY DEFAULT AS IDENTITY,
    authority_name  TEXT          NOT NULL,
    authority_type  TEXT          NOT NULL,
    contact_no      TEXT          NOT NULL,
    jurisdiction    TEXT          NOT NULL,
    base_latitude   NUMERIC(9,6)  NOT NULL,
    base_longitude  NUMERIC(9,6)  NOT NULL,
    radius_km       NUMERIC(7,2)  NOT NULL,
    CONSTRAINT pk_authority        PRIMARY KEY (authority_id),
    CONSTRAINT chk_authority_type  CHECK (authority_type IN ('POLICE', 'AMBULANCE', 'HOSPITAL', 'FIRE', 'HIGHWAY_PATROL')),
    CONSTRAINT chk_authority_lat   CHECK (base_latitude  BETWEEN -90  AND 90),
    CONSTRAINT chk_authority_lon   CHECK (base_longitude BETWEEN -180 AND 180),
    CONSTRAINT chk_authority_radius CHECK (radius_km > 0 AND radius_km <= 500),
    CONSTRAINT uq_authority_name_jurisdiction UNIQUE (authority_name, jurisdiction)
);

-- -----------------------------------------------------------------------------
-- Accidents and alerting
-- -----------------------------------------------------------------------------
CREATE TABLE accident_event (
    event_id          INT GENERATED BY DEFAULT AS IDENTITY,
    participant_id    INT          NOT NULL,
    impact_force      NUMERIC(6,2) NOT NULL,      -- peak acceleration in g
    latitude          NUMERIC(9,6) NOT NULL,
    longitude         NUMERIC(9,6) NOT NULL,
    detected_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    is_confirmed      BOOLEAN      NOT NULL,      -- false = rider cancelled the countdown
    motion_sample_id  TEXT,                       -- ObjectId of the MongoDB evidence document
    CONSTRAINT pk_accident_event              PRIMARY KEY (event_id),
    CONSTRAINT fk_accident_event_participant  FOREIGN KEY (participant_id) REFERENCES ride_participant (participant_id) ON DELETE CASCADE,
    CONSTRAINT chk_accident_event_force       CHECK (impact_force > 0 AND impact_force < 100),
    CONSTRAINT chk_accident_event_lat         CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT chk_accident_event_lon         CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT chk_accident_event_mongo_id    CHECK (motion_sample_id IS NULL OR motion_sample_id ~ '^[0-9a-f]{24}$')
);
CREATE INDEX ix_accident_event_participant ON accident_event (participant_id);

CREATE TABLE sos_alert (
    alert_id        INT GENERATED BY DEFAULT AS IDENTITY,
    event_id        INT         NOT NULL,
    channel         TEXT        NOT NULL DEFAULT 'IN_APP',
    sent_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    delivery_state  TEXT        NOT NULL DEFAULT 'PENDING',
    CONSTRAINT pk_sos_alert          PRIMARY KEY (alert_id),
    -- exactly one alert per accident, ever
    CONSTRAINT uq_sos_alert_event    UNIQUE (event_id),
    CONSTRAINT fk_sos_alert_event    FOREIGN KEY (event_id) REFERENCES accident_event (event_id) ON DELETE CASCADE,
    CONSTRAINT chk_sos_alert_channel CHECK (channel IN ('IN_APP', 'SMS_SIMULATED')),
    CONSTRAINT chk_sos_alert_delivery_state CHECK (delivery_state IN ('PENDING', 'DISPATCHED', 'PARTIAL', 'FAILED'))
);

CREATE TABLE alert_recipient (
    recipient_id    INT GENERATED BY DEFAULT AS IDENTITY,
    alert_id        INT  NOT NULL,
    recipient_kind  TEXT NOT NULL,
    user_id         INT,
    contact_id      INT,
    authority_id    INT,
    delivery_state  TEXT NOT NULL DEFAULT 'PENDING',
    attempted_at    TIMESTAMPTZ,
    CONSTRAINT pk_alert_recipient            PRIMARY KEY (recipient_id),
    CONSTRAINT fk_alert_recipient_alert      FOREIGN KEY (alert_id)     REFERENCES sos_alert (alert_id)             ON DELETE CASCADE,
    CONSTRAINT fk_alert_recipient_user       FOREIGN KEY (user_id)      REFERENCES app_user (user_id)               ON DELETE CASCADE,
    CONSTRAINT fk_alert_recipient_contact    FOREIGN KEY (contact_id)   REFERENCES emergency_contact (contact_id)   ON DELETE CASCADE,
    CONSTRAINT fk_alert_recipient_authority  FOREIGN KEY (authority_id) REFERENCES authority (authority_id)         ON DELETE RESTRICT,
    CONSTRAINT chk_alert_recipient_kind      CHECK (recipient_kind IN ('CO_RIDER', 'EMERGENCY_CONTACT', 'AUTHORITY')),
    CONSTRAINT chk_alert_recipient_delivery_state CHECK (delivery_state IN ('PENDING', 'DELIVERED', 'MANUAL_ACTION_REQUIRED', 'FAILED')),
    -- exactly one reference column is set, and it is the one matching the kind
    CONSTRAINT chk_alert_recipient_exactly_one CHECK (
        (recipient_kind = 'CO_RIDER'          AND user_id IS NOT NULL AND contact_id IS NULL     AND authority_id IS NULL) OR
        (recipient_kind = 'EMERGENCY_CONTACT' AND user_id IS NULL     AND contact_id IS NOT NULL AND authority_id IS NULL) OR
        (recipient_kind = 'AUTHORITY'         AND user_id IS NULL     AND contact_id IS NULL     AND authority_id IS NOT NULL)
    ),
    CONSTRAINT chk_alert_recipient_attempted CHECK ((delivery_state = 'PENDING') = (attempted_at IS NULL))
);
-- no recipient is notified twice for the same alert
CREATE UNIQUE INDEX ux_alert_recipient_user      ON alert_recipient (alert_id, user_id)      WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX ux_alert_recipient_contact   ON alert_recipient (alert_id, contact_id)   WHERE contact_id IS NOT NULL;
CREATE UNIQUE INDEX ux_alert_recipient_authority ON alert_recipient (alert_id, authority_id) WHERE authority_id IS NOT NULL;

-- Append-only audit trail. No foreign keys on purpose: the record of who was
-- notified must survive deletion of the ride, alert or recipient it describes.
-- Append-only is enforced by trg_alert_audit_append_only (05) and by REVOKE (02).
CREATE TABLE alert_audit (
    audit_id      BIGINT GENERATED ALWAYS AS IDENTITY,
    alert_id      INT         NOT NULL,
    recipient_id  INT         NOT NULL,
    attempted_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    outcome       TEXT        NOT NULL,
    CONSTRAINT pk_alert_audit         PRIMARY KEY (audit_id),
    CONSTRAINT chk_alert_audit_outcome CHECK (outcome IN ('DELIVERED', 'MANUAL_ACTION_REQUIRED', 'FAILED'))
);
CREATE INDEX ix_alert_audit_alert ON alert_audit (alert_id);

-- -----------------------------------------------------------------------------
-- Ride summary and route embedding (vector feature)
-- -----------------------------------------------------------------------------
CREATE TABLE ride_summary (
    ride_id             INT           NOT NULL,
    distance_km         NUMERIC(8,2)  NOT NULL,
    duration_min        NUMERIC(8,2)  NOT NULL,
    avg_speed_kmph      NUMERIC(6,2)  NOT NULL,
    max_speed_kmph      NUMERIC(6,2)  NOT NULL,
    stop_count          INT           NOT NULL,
    start_lat           NUMERIC(9,6)  NOT NULL,
    start_lon           NUMERIC(9,6)  NOT NULL,
    end_lat             NUMERIC(9,6)  NOT NULL,
    end_lon             NUMERIC(9,6)  NOT NULL,
    bbox_diagonal_km    NUMERIC(8,2)  NOT NULL,
    straightness_ratio  NUMERIC(5,4)  NOT NULL,
    route_embedding     vector(96),            -- filled by lib/vector after sp_end_ride
    computed_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT pk_ride_summary              PRIMARY KEY (ride_id),
    CONSTRAINT fk_ride_summary_ride         FOREIGN KEY (ride_id) REFERENCES ride (ride_id) ON DELETE CASCADE,
    CONSTRAINT chk_ride_summary_nonnegative CHECK (distance_km >= 0 AND duration_min >= 0 AND avg_speed_kmph >= 0
                                                   AND max_speed_kmph >= 0 AND stop_count >= 0 AND bbox_diagonal_km >= 0),
    CONSTRAINT chk_ride_summary_speeds      CHECK (max_speed_kmph >= avg_speed_kmph),
    CONSTRAINT chk_ride_summary_straightness CHECK (straightness_ratio BETWEEN 0 AND 1)
);
-- HNSW approximate nearest-neighbour index for cosine distance (<=>).
CREATE INDEX ix_ride_summary_embedding_hnsw
    ON ride_summary USING hnsw (route_embedding vector_cosine_ops);
